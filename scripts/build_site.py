def write(path: Path, content: str, check: bool, drift: list) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return
    rel = path.relative_to(ROOT).as_posix()
    if check:
        drift.append(rel)
    else:
        # Always LF: a Windows build and a Linux build must produce identical bytes,
        # otherwise --check flags drift on every platform switch.
        path.write_text(content, encoding="utf-8", newline="\n")
        print("wrote", rel)


