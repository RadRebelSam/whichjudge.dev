def apply_blocks(text: str, blocks: dict) -> str:
    for name, body in blocks.items():
        open_tag, close_tag = GEN_OPEN.format(name=name), GEN_CLOSE.format(name=name)
        if open_tag not in text or close_tag not in text:
            raise SystemExit(f"README.md is missing the {name} generated block markers")
        head, rest = text.split(open_tag, 1)
        _, tail = rest.split(close_tag, 1)
        text = head + open_tag + "\n" + body + "\n" + close_tag + tail
    return text


