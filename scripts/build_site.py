"""Generate every published number and page from results/.

site/copy.json holds editorial text only. This script joins it with
results/summary.json, results/calibration.json and
results/tfidf_baseline_summary.json and writes:

    site/data.js              RUN + TASKS consumed by site/app.js
    site/decision/<id>.html   one crawlable page per decision
    site/sitemap.xml
    site/robots.txt
    site/index.html           <meta> block between the meta markers

Run with --check to fail when the committed site disagrees with results/,
which is what stops the table from silently drifting from the receipts.
"""
