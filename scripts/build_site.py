def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def per_million(cost: float, n: int) -> float:
    return round(cost / n * 1e6, 2)


def e(s) -> str:
    return html.escape(str(s), quote=True)


def pct(x) -> str:
    return f"{x * 100:.1f}%"


def holm(pvalues: dict) -> dict:
    """Holm-Bonferroni adjusted p-values for one family of tests.

    Eleven McNemar tests at 0.05 each will crown winners by chance. Holm controls
    the family-wise error rate without Bonferroni's full conservatism. Applied
    separately to each comparison family, never across them.
    """
    order = sorted(pvalues.items(), key=lambda kv: kv[1])
    m = len(order)
    adjusted, running = {}, 0.0
    for i, (key, pv) in enumerate(order):
        running = max(running, min(1.0, (m - i) * pv))
        adjusted[key] = running
    return adjusted


def build_tasks(copy, summary, calib, tfidf, errors, modern, gatefile, windows):
    by_id = {r["task_id"]: r for r in summary}
    tf_by_id = {r["task_id"]: r for r in tfidf}
    mod_by_id = {r["task_id"]: r for r in (modern or {}).get("tasks", [])}
    # One Holm family per comparison: Jev vs Mini, TF-IDF vs Jev, current model vs Jev.
    holm_mini = holm({r["task_id"]: r["mcnemar"]["p_value"] for r in summary})
    holm_tfidf = holm({r["task_id"]: r["mcnemar_vs_jev"]["p_value"] for r in tfidf})
    holm_modern = holm({r["task_id"]: r["mcnemar_vs_jev"]["p_value"]
                        for r in (modern or {}).get("tasks", [])})
    # The "vs 4o-mini" columns are families of eleven tests too. They used to be
    # read at the raw 0.05, which is the same mistake the Jev columns had.
    holm_tfidf_mini = holm({r["task_id"]: r["mcnemar_vs_mini"]["p_value"] for r in tfidf})
    holm_modern_mini = holm({r["task_id"]: r["mcnemar_vs_mini"]["p_value"]
                             for r in (modern or {}).get("tasks", [])})
    out = []
    for c in copy["tasks"]:
        tid = c["id"]
        s = by_id[tid]
        t = tf_by_id[tid]
        mc = s["mcnemar"]
        n = s["n"]
        # One score for gating and calibration. summary.json's jev_gates thresholded
        # on 'confidence' while ECE used 'p_chosen'; gates.json uses p_chosen for both.
        gtab = gatefile[tid]["gates"]
        gcv = gatefile[tid]["cross_validated"]

        # ns is not an opinion: it is "McNemar did not clear 0.05 after Holm
        # correction across all eleven Jev-vs-Mini tests". Uncorrected, two rows
        # (offensive, news) looked significant that do not survive the family.
        p_holm = holm_mini[tid]
        derived_ns = p_holm >= 0.05
        if bool(c["ns"]) != derived_ns:
            raise SystemExit(
                f"{tid}: copy.json says ns={c['ns']} but Holm-adjusted p={p_holm:.3g} "
                f"(raw {mc['p_value']:.3g}) means ns={derived_ns}. Fix the copy, not the number."
            )
        # The reverse direction matters just as much: a row may not claim a winner
        # over Mini when McNemar declined to give it one. "neither" is about all the
        # models at once, so it is allowed to sit on top of an ns row.
        if derived_ns and c["verdict"] in ("replace", "dont"):
            raise SystemExit(
                f"{tid}: copy.json claims verdict={c['verdict']} but McNemar is ns "
                f"after Holm (p={p_holm:.3g}, raw {mc['p_value']:.3g}). Use \"mix\" or \"neither\"; the badge must not "
                f"crown a winner the test refused to."
            )

        auto = None
        for gate, v in sorted(gtab.items()):
            if (v["accuracy"] is not None and v["coverage"] >= 0.5
                    and (auto is None or v["accuracy"] > auto[1]["accuracy"])):
                auto = (gate, v)
        auto_slice = None
        if auto:
            gate, v = auto
            auto_slice = {
                "gate": float(gate),
                "acc": round(v["accuracy"], 4),
                "cov": round(v["coverage"], 4),
                "lift": round(v["accuracy"] - s["jev_acc"], 4),
                "cvAcc": gcv["accuracy_mean"],
                "cvLo": gcv["accuracy_lo"],
                "cvHi": gcv["accuracy_hi"],
            }

        # Editorial sentences quote measurements. After a re-run they go stale
        # silently, which is exactly the drift this build is supposed to prevent,
        # so every percentage in the prose must exist somewhere in this task's data.
        known = set()
        for value in (s["jev_acc"], s["mini_acc"], t["acc"]):
            known.add(round(value * 100, 1))
        for gate in gtab.values():
            if gate["accuracy"] is None:
                continue
            known.add(round(gate["accuracy"] * 100, 1))
            known.add(round(gate["coverage"] * 100, 1))
        known.add(round(abs(s["jev_acc"] - s["mini_acc"]) * 100, 1))
        md = mod_by_id.get(tid)
        if md:
            known.add(round(md["acc"] * 100, 1))
            known.add(round(md["wilson"]["lo"] * 100, 1))
            known.add(round(md["wilson"]["hi"] * 100, 1))
        for gate, v in gtab.items():
            if v["accuracy"] is None:
                continue
            known.add(round((v["accuracy"] - s["jev_acc"]) * 100, 1))
        if auto_slice:
            for key in ("acc", "cov", "lift"):
                known.add(round(abs(auto_slice[key]) * 100, 1))
        prof = errors.get(tid, {})
        for arm in prof.values():
            for stats in arm.get("per_class", {}).values():
                for field in ("recall", "missed_rate", "false_positive_rate"):
                    if stats.get(field) is not None:
                        known.add(round(stats[field] * 100, 1))
            for gate in arm.get("recall_at_gate", {}).values():
                for stats in gate.values():
                    if stats.get("recall_on_covered") is not None:
                        known.add(round(stats["recall_on_covered"] * 100, 1))
        for field in ("why", "gate", "rowNote"):
            if not c.get(field):
                continue
            for raw in re.findall(r"(\d+\.?\d*)\s*(?:%|pt)", c[field]):
                # Match at the precision the sentence was written at: "89%" may round
                # a measured 88.8, but "98.6%" must be a measured 98.6, not 98.9.
                decimals = len(raw.split(".")[1]) if "." in raw else 0
                quoted = float(raw)
                if quoted not in {round(k, decimals) for k in known}:
                    raise SystemExit(
                        f"{tid}: copy.json {field} quotes {raw} but no measurement in "
                        f"results/ matches it at that precision. Update the sentence, "
                        f"or the site states a stale number."
                    )

        def versus(key, loser):
            m = t[key]
            adj = holm_tfidf[tid] if key == "mcnemar_vs_jev" else holm_tfidf_mini[tid]
            if adj >= 0.05:
                return "ns"
            return "tfidf" if m["winner"] == "a" else loser

        bins = [
            {"lo": b["lo"], "n": b["n"], "conf": round(b["conf"], 3), "acc": round(b["acc"], 3)}
            for b in calib[tid]["p_chosen"]["bins"]
            if b["n"]
        ]
        out.append({
            "id": tid,
            "n": n,
            "title": c["title"],
            "replaces": c["replaces"],
            "dataset": c["dataset"],
            "labels": c["labels"],
            "verdict": c["verdict"],
            "ns": derived_ns,
            "why": c["why"],
            "gate": c["gate"],
            "goldTier": c["goldTier"],
            "rowNote": c.get("rowNote"),
            "rowNoteKind": c.get("rowNoteKind"),
            "goldNote": c["goldNote"],
            "sourceName": c["sourceName"],
            "sourceUrl": c["sourceUrl"],
            "mirrorUrl": c.get("mirrorUrl"),
            "samplesSha": s["samples_sha256"][:12],
            "schemaSha": s["schema_sha256"][:12],
            "jev": {
                "acc": s["jev_acc"],
                "lo": round(s["jev_wilson"]["lo"], 3),
                "hi": round(s["jev_wilson"]["hi"], 3),
                "p50": round(s["jev_p50_ms"]),
                "p95": round(s["jev_p95_ms"]),
                "conf": round(s["jev_mean_conf"], 3),
                "cost": s["jev_cost"],
                "perM": per_million(s["jev_cost"], n),
            },
            "mini": {
                "acc": s["mini_acc"],
                "lo": round(s["mini_wilson"]["lo"], 3),
                "hi": round(s["mini_wilson"]["hi"], 3),
                "p50": round(s["mini_p50_ms"]),
                "p95": round(s["mini_p95_ms"]),
                "cost": s["mini_cost"],
                "perM": per_million(s["mini_cost"], n),
            },
            "mcnemar": {
                "p": float(f"{mc['p_value']:.3g}"),
                "pHolm": float(f"{p_holm:.3g}"),
                "winner": mc["winner"] if not derived_ns else "ns",
                "b": mc["jev_only_correct"],
                "c": mc["mini_only_correct"],
            },
            "tfidf": {
                "acc": t["acc"],
                "lo": round(t["wilson"]["lo"], 3),
                "hi": round(t["wilson"]["hi"], 3),
                # A batched predict() over all rows divided by the row count: a mean
                # per row, not a median, so it is not called p50 anywhere.
                "meanUsBatched": round(t["predict_mean_ms_per_row_batched"] * 1000),
                "trainN": t["train_n"],
                "vsJev": versus("mcnemar_vs_jev", "jev"),
                "vsMini": versus("mcnemar_vs_mini", "mini"),
                "pJev": float(f"{t['mcnemar_vs_jev']['p_value']:.3g}"),
                "pJevHolm": float(f"{holm_tfidf[tid]:.3g}"),
                "pMini": float(f"{t['mcnemar_vs_mini']['p_value']:.3g}"),
                "pMiniHolm": float(f"{holm_tfidf_mini[tid]:.3g}"),
            },
            "run": windows[tid],
            "ece": {
                "ece": round(calib[tid]["p_chosen"]["ece"], 3),
                "mce": round(calib[tid]["p_chosen"]["mce"], 3),
                "bins": bins,
            },
            "gates": {
                k: {"cov": v["coverage"], "acc": round(v["accuracy"], 3)}
                for k, v in gtab.items() if v["accuracy"] is not None
            },
            "errors": errors.get(tid),
            "modern": ({
                "model": md["model"],
                "acc": md["acc"],
                "lo": round(md["wilson"]["lo"], 3),
                "hi": round(md["wilson"]["hi"], 3),
                "p50": round(md["p50_ms"]),
                "tokens": md["tokens_per_call"],
                "vsJev": ("ns" if holm_modern.get(tid, 1.0) >= 0.05
                          else ("modern" if md["mcnemar_vs_jev"]["winner"] == "a" else "jev")),
                "vsMini": ("ns" if holm_modern_mini.get(tid, 1.0) >= 0.05
                           else ("modern" if md["mcnemar_vs_mini"]["winner"] == "a" else "mini")),
                "pJev": float(f"{md['mcnemar_vs_jev']['p_value']:.3g}"),
                "pJevHolm": float(f"{holm_modern[tid]:.3g}"),
                "pMini": float(f"{md['mcnemar_vs_mini']['p_value']:.3g}"),
                "pMiniHolm": float(f"{holm_modern_mini[tid]:.3g}"),
            } if md else None),
            "autoSlice": auto_slice,
        })
    return out



def run_windows(summary) -> tuple[list[dict], dict]:
    """Which invocation of run_eval.py produced each row, read off the receipts.

    summary.json carries a run_id only on rows written after that field existed,
    so counting run ids under-reports. Every receipt has a UTC stamp, and rows
    whose stamps sit within RUN_GAP of each other came from one invocation.
    """
    spans = []
    for row in summary:
        rec = load(RECEIPTS / f"{row['task_id']}.json")
        stamps = [r["utc"] for arm in ("jev", "gpt4o_mini") for r in rec[arm] if r.get("utc")]
        spans.append((min(stamps), max(stamps), row["task_id"]))
    spans.sort()
    runs: list[dict] = []
    for start, end, tid in spans:
        if runs and datetime.fromisoformat(start) - datetime.fromisoformat(runs[-1]["end"]) <= RUN_GAP:
            runs[-1]["end"] = max(runs[-1]["end"], end)
            runs[-1]["tasks"].append(tid)
        else:
            runs.append({"start": start, "end": end, "tasks": [tid]})
    per_task = {}
    for i, r in enumerate(runs, 1):
        r["index"] = i
        for tid in r["tasks"]:
            per_task[tid] = {"index": i, "of": len(runs), "start": r["start"], "end": r["end"]}
    return runs, per_task


